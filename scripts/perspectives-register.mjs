#!/usr/bin/env node
// scripts/perspectives-register.mjs — the fold's standing register of who
// SPEAKS in the corpus, who is SPOKEN ABOUT without a voice, and who is not
// even named.
//
// Every perspective is measured on two independent axes:
//   about  — the group is a topic somewhere in the corpus (subject-side)
//   by     — a member of the group is the author / first-person voice
// Then each is classed into one of three tiers:
//   VOICED             by > 0            — the people hold their own words
//   DISCUSSED, EMPTY   about > 0, by = 0 — spoken about, never speaking
//   NOT-DISCUSSED      about = 0, by = 0 — absent altogether
//
// The register file (PERSPECTIVES-REGISTER.md at the repo root) is
// REGENERATED by this script on every run — it is a live measurement, not a
// ledger. The great scroll's ledger, by contrast, is append-only; each audit
// adds one dated outcome line there. A run with `--scroll <relpath>` appends
// that outcome to the named scroll automatically.
//
//   node scripts/perspectives-register.mjs [--json] [--scroll ../GREAT-SCROLL.md]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const SKIP_DIRS = new Set(['.git', 'node_modules']);

function walk(dir, rel) {
  const abs = path.join(dir, rel);
  if (!fs.existsSync(abs)) return [];
  const out = [];
  for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    if (entry.name.startsWith('.')) continue;
    const r2 = path.join(rel, entry.name);
    if (entry.isDirectory()) out.push(...walk(dir, r2));
    else if (/\.txt$/.test(entry.name)) out.push(r2);
  }
  return out;
}

