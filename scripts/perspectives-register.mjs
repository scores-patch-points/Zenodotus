const VOICED = 'voiced';
const EMPTY = 'discussed-but-empty';
const ABSENT = 'not-discussed';

function main() {
  const files = walk(ROOT, '');
  const audit = GROUPS.map((g) => {
    const about = [];
    const by = [];
    for (const f of files) {
      let text;
      try { text = fs.readFileSync(path.join(ROOT, f), 'utf8').slice(0, 200000); }
      catch { continue; }
      if (g.subject.test(text)) about.push(f);
      const head = text.slice(0, 4000);
      const byAuthor = new RegExp(`(?:by|author:).{0,80}?${g.names.source}`, 'i').test(f + '\n' + head);
      const byTag = g.tags ? new RegExp(`perspective:\\s*.{0,40}?${g.tags.source}`, 'i').test(head) : false;
      if (byAuthor || byTag) by.push(f);
    }
    const tier = by.length > 0 ? VOICED : (about.length > 0 ? EMPTY : ABSENT);
    return { id: g.id, name: g.name, about: about.length, by: by.length, tier, aboutSamples: about.slice(0, 6), bySamples: by.slice(0, 6) };
  });

  const summarize = (g) => `[${g.name}] about=${g.about} by=${g.by} → ${g.tier}`;

  // JSON mode: just the structured report.
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify({ schema: 'PerspectivesRegister@1', scanned: files.length, audit }, null, 2));
    return;
  }

  // Markdown: regenerate PERSPECTIVES-REGISTER.md at the repo root.
  const rows = audit.map((g) => `| ${g.name} | ${g.about} | ${g.by} | ${(g.by / (g.about || 1) * 100).toFixed(0)}% | ${g.tier} |`).join('\n');
  const tiers = {
    [VOICED]: audit.filter((g) => g.tier === VOICED),
    [EMPTY]: audit.filter((g) => g.tier === EMPTY),
    [ABSENT]: audit.filter((g) => g.tier === ABSENT),
  };
  const md = [
    '# Perspectives Register',
    '',
    '*The fold\'s standing measurement of who SPEAKS, who is spoken about without a voice, and who is not even named. Regenerated by `node scripts/perspectives-register.mjs` — a measurement, not a ledger. The great scroll carries the append-only audit trail.*',
    '',
    `Scanned: **${files.length} documents**.`,
    '',
    '| Perspective | Spoken about | First-person | Voice ratio | Tier |',
    '|---|---|---|---|---|',
    rows,
    '',
    '## Tiers',
    '',
    `- **Voiced (${tiers[VOICED].length})** — hold their own words: ${tiers[VOICED].map((g) => g.name).join('; ') || 'none yet'}`,
    `- **Discussed-but-empty (${tiers[EMPTY].length})** — spoken about, never speaking: ${tiers[EMPTY].map((g) => g.name).join('; ') || 'none'}`,
    `- **Not-discussed (${tiers[ABSENT].length})** — absent altogether: ${tiers[ABSENT].map((g) => g.name).join('; ') || 'none'}`,
    '',
    '*Falsifying control: re-running the script reproduces the table; a fresh scan for any group that finds a first-person text the audit missed falsifies that row\'s tier, not the method.*',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, 'PERSPECTIVES-REGISTER.md'), md + '\n');

  // Ledger append: one dated line in the scroll when requested.
  console.log('\n' + audit.map(summarize).join('\n'));
  const scrollArg = process.argv.find((a) => a.startsWith('--scroll='));
  if (scrollArg) {
    const scrollPath = path.resolve(__dirname, '..', scrollArg.split('=')[1]);
    if (fs.existsSync(scrollPath)) {
      const line = `- ${new Date().toISOString()}Z — **Perspectives audit.** ${audit.length} perspectives classed: ${tiers[VOICED].length} voiced, ${tiers[EMPTY].length} discussed-but-empty, ${tiers[ABSENT].length} not-discussed. Full register: [PERSPECTIVES-REGISTER.md](PERSPECTIVES-REGISTER.md). Empty-but-discussed: ${tiers[EMPTY].map((g) => g.name).join('; ')}. Not-discussed: ${tiers[ABSENT].map((g) => g.name).join('; ')}. *(target: every empty count falls toward zero as its people's public-domain testimony is fetched.)*`;
      fs.appendFileSync(scrollPath, '\n' + line + '\n');
      console.log('\nappended audit line to ' + scrollPath);
    }
  }
}

main();